import type { RawProcess } from '../../tm1Rest/processApi';
import type { OverviewRow, KpiValue } from '../../webviews/objectOverview/overviewTypes';

const SECTION_FIELDS: [keyof RawProcess, string][] = [
  ['PrologProcedure', 'P'], ['MetadataProcedure', 'M'], ['DataProcedure', 'D'], ['EpilogProcedure', 'E'],
];

/** Strip generated `#****...` marker block TM1 injects, then check real code. */
function bodyText(proc: string | undefined): string {
  if (!proc) { return ''; }
  return proc
    .split(/\r?\n/)
    .filter(l => !/^#(\*{2,}|Generated by|\s*$)/.test(l))
    .join('\n')
    .trim();
}

export function usedSections(p: RawProcess): string[] {
  const out: string[] = [];
  for (const [field, label] of SECTION_FIELDS) {
    if (bodyText(p[field] as string | undefined)) { out.push(label); }
  }
  return out;
}

export function classifyDatasource(type?: string): string {
  switch ((type ?? 'None')) {
    case 'None': return 'none';
    case 'ODBC': return 'ODBC';
    case 'TM1CubeView': return 'view';
    case 'TM1DimensionSubset': return 'dimension';
    case 'ASCII': return 'file';
    default: return type ?? 'none';
  }
}

export function hasDocComment(p: RawProcess): boolean {
  const first = (p.PrologProcedure ?? '').split(/\r?\n/).find(l => l.trim() !== '') ?? '';
  return first.trimStart().startsWith('#');
}

const CALL_RE = /\b(?:ExecuteProcess|RunProcess)\s*\(\s*'((?:[^']|'')*)'/gi;

export function procCalls(p: RawProcess): string[] {
  const code = [p.PrologProcedure, p.MetadataProcedure, p.DataProcedure, p.EpilogProcedure].join('\n');
  const names = new Set<string>();
  let m: RegExpExecArray | null;
  CALL_RE.lastIndex = 0;
  while ((m = CALL_RE.exec(code)) !== null) { names.add(m[1].replace(/''/g, "'")); }
  return [...names];
}

function lineCount(p: RawProcess): number {
  return SECTION_FIELDS.reduce((n, [f]) => n + ((p[f] as string | undefined)?.split(/\r?\n/).length ?? 0), 0);
}

export function buildProcessRows(raw: RawProcess[]): OverviewRow[] {
  // TM1 process names are case-insensitive at call time (ExecuteProcess/RunProcess),
  // so matching/keying is lowercased here. Display values (row names, callsByProc)
  // keep their original casing.
  const calledBy = new Map<string, number>();
  const callsByProc = new Map<string, string[]>();
  for (const p of raw) {
    const calls = procCalls(p);
    callsByProc.set(p.Name, calls);
    for (const c of calls) {
      const key = c.toLowerCase();
      calledBy.set(key, (calledBy.get(key) ?? 0) + 1);
    }
  }
  return raw.map(p => ({
    id: p.Name,
    isControl: p.Name.startsWith('}'),
    cells: {
      name: p.Name,
      params: p.Parameters?.length ?? 0,
      datasource: classifyDatasource(p.DataSource?.Type),
      sections: usedSections(p),
      lines: lineCount(p),
      security: !!p.HasSecurityAccess,
      calls: callsByProc.get(p.Name)?.length ?? 0,
      calledBy: calledBy.get(p.Name.toLowerCase()) ?? 0,
      lastRun: null, // filled lazily
      duration: null, // filled lazily
      __hasDoc: hasDocComment(p), // internal, not a column
    },
  }));
}

export function buildProcessKpis(rows: OverviewRow[]): KpiValue[] {
  const total = rows.length;
  const noDoc = rows.filter(r => r.cells.__hasDoc !== true).map(r => r.id);
  const dsCounts: Record<string, number> = {};
  for (const r of rows) { const d = String(r.cells.datasource); dsCounts[d] = (dsCounts[d] ?? 0) + 1; }
  const dsSummary = Object.entries(dsCounts).map(([k, v]) => `${v} ${k}`).join(' · ');
  return [
    { key: 'total', label: 'Processes', value: String(total) },
    { key: 'datasource', label: 'Datasource', value: dsSummary || '—' },
    { key: 'noDoc', label: 'No doc comment', value: String(noDoc.length), rowIds: noDoc },
  ];
}
